export type Locale = (typeof LOCALES)[number];
export const DEFAULT_LOCALE: Locale = "en";

export type Dict = Record<string, unknown>;

export function getByPath(dict: Dict, path: string): unknown {
  const parts = path.split(".");
  let current: unknown = dict;
  for (const part of parts) {
    if (current === null || typeof current !== "object") return undefined;
    current = (current as Record<string, unknown>)[part];
  }
  return current;
}

function interpolate(value: string, params?: Record<string, string | number>) {
  if (!params) return value;
  return value.replace(/\{\{(\w+)\}\}/g, (_, key) =>
    String(params[key] ?? `{{${key}}}`),
  );
}

export function translate(
  locale: Locale,
  path: string,
  params?: Record<string, string | number>,
): string {
  const primary = getByPath(DICTIONARIES[locale] as Dict, path);
  if (typeof primary === "string") return interpolate(primary, params);
  const fallback = getByPath(DICTIONARIES[DEFAULT_LOCALE] as Dict, path);
  if (typeof fallback === "string") return interpolate(fallback, params);
  return path;
}

export function detectLocale(): Locale {
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  const params = new URLSearchParams(window.location.search);
  const lng = params.get("lng");
  if (lng && LOCALES.includes(lng as Locale)) return lng as Locale;
  const stored = window.localStorage.getItem("locale") as Locale | null;
  if (stored && LOCALES.includes(stored)) return stored;
  const nav = (navigator.language || DEFAULT_LOCALE).toLowerCase();
  const exact = LOCALES.find((l) => nav === l);
  if (exact) return exact;
  const prefix = LOCALES.find((l) => nav.startsWith(`${l}-`));
  if (prefix) return prefix;
  return DEFAULT_LOCALE;
}

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (path: string, params?: Record<string, string | number>) => string;
}

export const I18nContext = createContext<I18nContextValue>({
  locale: DEFAULT_LOCALE,
  setLocale: () => {},
  t: (path) => path,
});

export function useI18n() {
  return useContext(I18nContext);
}

export function getLocaleName(locale: Locale): string {
  try {
    const name = new Intl.DisplayNames(locale, {
      type: "language",
      languageDisplay: "standard",
    }).of(locale);
    if (name) return name;
  } catch {
    // ignore
  }
  return locale;
}

